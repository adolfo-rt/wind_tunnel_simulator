import { describe, it, expect } from 'vitest';
import { writeFileSync } from 'node:fs';
import { ROSTER } from '../src/aircraft/roster';
import { analyseAircraft } from '../src/physics/performance/analyse';
import { CRUISE_DATASET, type CruiseDatum } from '../src/physics/performance/cruiseDataset';

/**
 * The precomputed cruise figures, and the guarantee that they are still true.
 *
 * The chart needs all twenty-one aircraft at once and a trimmed solve takes about a
 * second and a half each, so the roster is solved ahead of time and committed. That is
 * a cache, and a cache that nobody checks is a lie waiting to happen - the model moves,
 * the file does not, and the chart quietly goes on showing last month's physics.
 *
 * So the dataset is regenerated by this file and verified by this file. `npm run dataset`
 * writes it; every ordinary test run recomputes the whole roster and fails if the
 * committed numbers have drifted. It costs the suite about half a minute, which is the
 * price of the chart being honest.
 */

function analyse(): CruiseDatum[] {
  return ROSTER.map((spec) => {
    const a = analyseAircraft(spec);
    return {
      id: spec.id,
      year: spec.firstFlightYear,
      spanEfficiency: round(a.spanEfficiency),
      angleDeg: round(a.angleDeg),
      stabiliserDeg: round(a.stabiliserDeg),
      tailLiftFraction: round(a.tailLiftFraction),
      liftCoefficient: round(a.liftCoefficient),
      liftToDrag: round(a.cruise.liftToDrag),
      publishedLiftToDrag: spec.reference.cruiseLD,
      fuelPerSeat100km: round(a.cruise.fuelPerSeat100km),
      fuelPerKm: round(a.cruise.fuelPerKm),
      induced: round(a.cruise.induced),
      parasite: round(a.cruise.parasite),
      wave: round(a.cruise.wave),
      totalDrag: round(a.cruise.totalDrag),
      parasiteParts: a.cruise.parasiteParts.map((p) => ({ name: p.name, force: round(p.force) })),
      wettedAreaM2: round(a.cruise.wettedAreaM2),
      divergenceMach: round(a.cruise.divergenceMach),
      applicable: a.cruise.applicable,
      limitation: a.cruise.limitation,
      trustworthy: a.trustworthy,
    };
  });
}

/** Six figures is far more than the model can claim and keeps the file diffable. */
function round(value: number): number {
  return Number(value.toPrecision(6));
}

describe('the precomputed cruise dataset', () => {
  it('matches a fresh solve of the whole roster', () => {
    const fresh = analyse();

    if (process.env.WRITE_DATASET) {
      writeFileSync('src/physics/performance/cruiseDataset.ts', render(fresh));
      return;
    }

    expect(
      CRUISE_DATASET.map((d) => d.id),
      'the dataset no longer covers the roster - run `npm run dataset`',
    ).toEqual(fresh.map((d) => d.id));

    for (const computed of fresh) {
      const stored = CRUISE_DATASET.find((d) => d.id === computed.id)!;
      const message = `${computed.id} has drifted - run \`npm run dataset\``;
      expect(stored.applicable, message).toBe(computed.applicable);
      if (!computed.applicable) continue;
      close(stored.liftToDrag, computed.liftToDrag, message);
      close(stored.fuelPerSeat100km, computed.fuelPerSeat100km, message);
      close(stored.spanEfficiency, computed.spanEfficiency, message);
      close(stored.totalDrag, computed.totalDrag, message);
      close(stored.induced, computed.induced, message);
      close(stored.parasite, computed.parasite, message);
    }
  }, 900000);
});

/** Half a per cent: wide enough to survive a harmless refactor, narrow enough to catch a real change. */
function close(stored: number, computed: number, message: string): void {
  const scale = Math.max(Math.abs(computed), 1e-9);
  expect(Math.abs(stored - computed) / scale, `${message} (${stored} vs ${computed})`).toBeLessThan(
    0.005,
  );
}

function render(data: CruiseDatum[]): string {
  return `/**
 * Cruise performance for the whole roster, solved ahead of time.
 *
 * GENERATED FILE - do not edit by hand. Run \`npm run dataset\` to rebuild it.
 *
 * Every number here comes from the same code the application runs: the aircraft is
 * built, trimmed to its cruise weight with no pitching moment left over, and the wake
 * integrated in the Trefftz plane. It is committed rather than computed in the browser
 * because a trimmed solve is about a second and a half per aircraft and the chart wants
 * all of them at once.
 *
 * \`tests/cruiseDataset.test.ts\` recomputes the roster on every test run and fails if
 * anything here has drifted, so this file cannot silently fall behind the model.
 */

export interface CruiseDatum {
  id: string;
  year: number;
  /** Simulated: from the trimmed vortex lattice. */
  spanEfficiency: number;
  angleDeg: number;
  stabiliserDeg: number;
  tailLiftFraction: number;
  liftCoefficient: number;
  /** Derived: simulated induced drag plus correlated parasite and wave drag. */
  liftToDrag: number;
  /** Published: the book figure, for comparison only. */
  publishedLiftToDrag: number;
  fuelPerSeat100km: number;
  fuelPerKm: number;
  induced: number;
  parasite: number;
  wave: number;
  totalDrag: number;
  parasiteParts: Array<{ name: string; force: number }>;
  wettedAreaM2: number;
  divergenceMach: number;
  /** False when the correlations do not describe this aircraft's cruise. */
  applicable: boolean;
  limitation?: string;
  trustworthy: boolean;
}

export const CRUISE_DATASET: CruiseDatum[] = ${JSON.stringify(data, null, 2)};

export function cruiseDatumFor(id: string): CruiseDatum | undefined {
  return CRUISE_DATASET.find((entry) => entry.id === id);
}
`;
}
